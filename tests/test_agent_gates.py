"""Review gates: one open question per session, picks from that session only, explicit submit or cancel."""
import unittest

from agent_bridge_support import AgentApp, add_round, add_users, memory_database, temporary_storage
from server.api.session import router as session_router
from server.models import ChatSession, GeneratedImage, ReviewGate


class AgentGateTests(unittest.TestCase):
    def setUp(self):
        self.engine, self.sessions = memory_database(self)
        add_users(self.sessions, 'one', 'two')
        temporary_storage(self)
        self.urls = [f'/uploads/generated/1/{name}.png' for name in 'abc']
        add_round(self.sessions, 'session', 1, 'agent-round', self.urls[:2], create_session=True)
        # A round the user generated by hand in the same session is pickable too; it was stored relative.
        add_round(self.sessions, 'session', 1, 'manual-round', ['generated/1/c.png'])
        add_round(self.sessions, 'elsewhere', 1, 'other-round', ['/uploads/generated/1/d.png'], create_session=True)
        add_round(self.sessions, 'theirs', 2, 'their-round', ['/uploads/generated/2/e.png'], create_session=True)
        self.app = AgentApp(self, self.sessions, routers=(session_router,))
        self.client = self.app.client

    def open_gate(self, **fields):
        body = {'session_id': 'session', 'question': '选一张侧视图', 'job': 'heroine', 'step': 'candidates', **fields}
        return self.client.post('/api/agent/gates', json=body)

    def gate_id(self, **fields):
        response = self.open_gate(**fields)
        self.assertEqual(response.status_code, 200, response.text)
        return response.json()['gate_id']

    def picks(self, gate_id, *urls):
        return self.client.put(f'/api/agent/gates/{gate_id}/picks', json={'picks': [{'url': url} for url in urls]})

    def submit(self, gate_id, decision='approve', **fields):
        return self.client.post(f'/api/agent/gates/{gate_id}/submit', json={'decision': decision, **fields})

    def test_one_open_gate_per_session_unless_replaced(self):
        first = self.gate_id(max_picks=2)
        self.assertEqual(self.open_gate().status_code, 409)
        second = self.gate_id(replace_open=True)
        gates = {gate['gate_id']: gate for gate in self.client.get('/api/agent/gates', params={'session_id': 'session'}).json()['gates']}
        self.assertEqual((gates[first]['status'], gates[first]['cancel_reason']), ('cancelled', '已被新的审核替换'))
        self.assertEqual(gates[second]['status'], 'open')
        self.assertEqual([gate['gate_id'] for gate in self.app.fields('agent_gate')], [first, first, second])
        self.assertEqual(self.open_gate(session_id='theirs').status_code, 404)
        self.assertEqual(self.open_gate(min_picks=3, max_picks=2).status_code, 422)
        open_only = self.client.get('/api/agent/gates', params={'status': 'open'}).json()['gates']
        self.assertEqual([gate['gate_id'] for gate in open_only], [second])

    def test_picks_resolve_to_results_of_this_session_only(self):
        gate_id = self.gate_id(max_picks=2)
        response = self.picks(gate_id, self.urls[1], 'http://example.test/uploads/generated/1/c.png')
        self.assertEqual(response.status_code, 200, response.text)
        self.assertEqual(response.json()['picks'], [
            {'url': self.urls[1], 'message_id': 'agent-round-reply', 'image_index': 1, 'seed': 101},
            {'url': self.urls[2], 'message_id': 'manual-round-reply', 'image_index': 0, 'seed': 100},
        ])
        for url in ('/uploads/generated/1/d.png', '/uploads/generated/2/e.png', '/uploads/../secret', 'data:image/png;base64,AA'):
            with self.subTest(url=url):
                self.assertEqual(self.picks(gate_id, url).status_code, 422)
        self.assertEqual(self.picks(gate_id, *self.urls).status_code, 422)
        self.assertEqual(self.picks(gate_id, self.urls[0], self.urls[0]).json()['picks'][0]['url'], self.urls[0])
        self.app.user_id = 2
        self.assertEqual(self.picks(gate_id, self.urls[0]).status_code, 404)

    def test_approve_needs_enough_live_picks_and_closes_the_gate(self):
        gate_id = self.gate_id(min_picks=1, max_picks=1)
        self.assertEqual(self.submit(gate_id).status_code, 422)
        self.picks(gate_id, self.urls[0])
        with self.sessions() as db:
            db.query(GeneratedImage).filter_by(file_path=self.urls[0]).delete()
            db.commit()
        self.assertEqual(self.submit(gate_id).status_code, 422, 'a result deleted after picking cannot be approved')
        response = self.submit(gate_id, picks=[{'url': self.urls[1]}], note='  就它了  ')
        self.assertEqual(response.status_code, 200, response.text)
        gate = response.json()
        self.assertEqual((gate['status'], gate['decision'], gate['note']), ('submitted', 'approve', '就它了'))
        self.assertEqual([pick['url'] for pick in gate['picks']], [self.urls[1]])
        self.assertIsNotNone(gate['submitted_at'])
        self.assertEqual(self.submit(gate_id).status_code, 409)
        self.assertEqual(self.picks(gate_id, self.urls[1]).status_code, 409)
        self.assertEqual(self.client.get(f'/api/agent/gates/{gate_id}').json()['status'], 'submitted')

    def test_redo_and_confirm_only_gates(self):
        gate_id = self.gate_id(max_picks=2)
        gate = self.submit(gate_id, 'redo', note='脸再圆一点').json()
        self.assertEqual((gate['decision'], gate['picks'], gate['note']), ('redo', [], '脸再圆一点'))
        confirm = self.gate_id(min_picks=1, max_picks=0)
        self.assertEqual(self.client.get(f'/api/agent/gates/{confirm}').json()['min_picks'], 0)
        self.assertEqual(self.picks(confirm, self.urls[0]).status_code, 422)
        self.assertEqual(self.submit(confirm).json()['decision'], 'approve')

    def test_cancel_and_session_deletion(self):
        gate_id = self.gate_id()
        cancelled = self.client.post(f'/api/agent/gates/{gate_id}/cancel', json={'reason': '用户在对话里回答了'}).json()
        self.assertEqual((cancelled['status'], cancelled['cancel_reason']), ('cancelled', '用户在对话里回答了'))
        self.assertEqual(self.client.post(f'/api/agent/gates/{gate_id}/cancel', json={}).status_code, 409)
        self.gate_id()
        self.assertEqual(self.client.delete('/api/chat/sessions/session').status_code, 200)
        with self.sessions() as db:
            self.assertEqual(db.query(ReviewGate).count(), 0)
            self.assertEqual(db.query(ChatSession).filter_by(session_id='session').count(), 0)
        self.assertEqual(self.client.get(f'/api/agent/gates/{gate_id}').status_code, 404)


if __name__ == '__main__':
    unittest.main()
